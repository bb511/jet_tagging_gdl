#!/bin/bash
# Run the evaluation blocks of a run*_eval.sh catalogue.
#
# Each block tests every checkpoint its training run's manifest names and
# appends one row to the results table. Local mode queues the selected blocks
# behind a single nohup, one GPU at a time; cluster mode gives each its own
# submitit driver.
#
# A cluster training ran as a multirun and wrote to <sweep.dir>/0, so --cluster
# rewrites both manifest paths to match: cluster-trained checkpoints have to be
# evaluated with --cluster, or the manifests are not found.
#
# A non-baseline block carries a second manifest, the baseline run it is scored
# against. Its absence is reported but does not hold the block back: eval then
# writes the row without the delta, confidence-interval and p-value columns.
#
# Usage (from the repository root):
#   bash scripts/cluster/submit_eval.sh --list    scripts/hls4ml/rundeepsets_eval.sh
#   bash scripts/cluster/submit_eval.sh --dry-run scripts/hls4ml/rundeepsets_eval.sh
#   bash scripts/cluster/submit_eval.sh --only nconst16 --gpu 0 scripts/hls4ml/rundeepsets_eval.sh
#   bash scripts/cluster/submit_eval.sh --cluster clariden scripts/hls4ml/rundeepsets_eval.sh
#
#   --list             list the blocks in the catalogue and exit
#   --dry-run          print the full commands without running anything; works
#                      off the cluster, so it needs neither the env nor the data
#   --only <sel>       comma-separated label substrings ('symm_so2', 'nconst150')
#                      or 1-based indices; default is every block in the file
#   --gpu <i>          rewrite trainer.devices to this GPU (local mode)
#   --cluster <c>      euler | clariden: one submitit job per block
#   --timeout-min <n>  slurm time limit per job (default 240)
#   --hf-cache <p>     value for HF_HUB_CACHE; default is the one .env exports
#
# Extra hydra overrides after the file name are appended to every command; hydra
# takes the last of a duplicated override, so they win over the file's value.
set -eu

# shellcheck source=scripts/cluster/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

only=""
dry=0
list=0
gpu=""
cluster=""
timeout_min=240
hf_cache=""

while [ $# -gt 0 ]; do
    case "$1" in
        --dry-run) dry=1; shift ;;
        --list) list=1; shift ;;
        --only) only="${2:?--only needs a value}"; shift 2 ;;
        --gpu) gpu="${2:?--gpu needs an index}"; shift 2 ;;
        --cluster) cluster="${2:?--cluster needs a name}"; shift 2 ;;
        --timeout-min) timeout_min="${2:?--timeout-min needs a number}"; shift 2 ;;
        --hf-cache) hf_cache="${2:?--hf-cache needs a path}"; shift 2 ;;
        --) shift; break ;;
        -*) echo "unknown option: $1" >&2; exit 2 ;;
        *) break ;;
    esac
done

usage="usage: submit_eval.sh [--list|--dry-run] [--only sel] [--gpu i] [--cluster c]"
usage="$usage [--timeout-min n] [--hf-cache p] <run*_eval.sh> [overrides...]"
file=${1:?$usage}
shift || true
extra="$*"

require_repo_root
[ -f "$file" ] || { echo "no such file: $file" >&2; exit 1; }

cmds=$(extract_cmds "$file")
n_total=$(printf "%s\n" "$cmds" | grep -c . || true)
if [ "$n_total" -eq 0 ]; then
    echo "No evaluation commands found in $file" >&2
    exit 1
fi

if [ "$list" -eq 1 ]; then
    printf "%-3s %-34s %-8s %s\n" "#" "block" "manifest" "path"
    i=0
    while IFS= read -r cmd; do
        i=$((i + 1))
        manifest=$(field "$cmd" 'checkpoint_manifest_path')
        printf "%-3s %-34s %-8s %s\n" "$i" "$(block_label "$cmd")" \
            "$([ -f "$manifest" ] && echo yes || echo MISSING)" "$manifest"
    done <<EOF
$cmds
EOF
    exit 0
fi

load_env
[ -z "$hf_cache" ] || export HF_HUB_CACHE="$hf_cache"
[ "$dry" -eq 1 ] || require_hf_cache

launcher=""
if [ -n "$cluster" ]; then
    launcher=" -m $(cluster_prefix "$cluster" "$timeout_min")"
    command -v sbatch >/dev/null 2>&1 || echo "warning: sbatch not on PATH - are you on $cluster?" >&2
fi

# PYTHON=/path/to/env/bin/python3 skips activation; --dry-run needs no env.
PYTHON=${PYTHON:-python3}
[ "$dry" -eq 1 ] || require_imports "$PYTHON" "hydra, lightning" \
    "conda activate jet_tagging_gdl" \
    "(or re-run with PYTHON=/path/to/env/bin/python3)"

stem="$(basename "$(dirname "$file")")_$(basename "$file" .sh)"
logdir="logs/submit/$stem"
run_ts=$(date +%Y-%m-%d_%H-%M-%S)
[ "$dry" -eq 1 ] || mkdir -p "$logdir"

# Local mode collects the selected commands here for one background queue.
queue="$logdir/queue_${run_ts}${gpu:+_gpu$gpu}.sh"
if [ "$dry" -eq 0 ] && [ -z "$cluster" ]; then
    printf '#!/bin/bash\n# Generated by submit_eval.sh on %s from %s.\n' "$run_ts" "$file" > "$queue"
    # No 'set -e': one block that dies must not take the rest of the queue with it.
    printf 'cd %s || exit 1\n' "$PWD" >> "$queue"
fi

i=0
n_sub=0
n_missing=0
while IFS= read -r cmd; do
    i=$((i + 1))
    label=$(block_label "$cmd")
    selected "$i" "$label" || continue

    if [ -n "$cluster" ]; then
        # One GPU per slurm job; the run dir becomes a sweep dir and both
        # manifest paths pick up the '/0/' of the training multirun.
        cmd=$(to_sweep_dir "$(pin_gpu "$cmd" 0)")
    elif [ -n "$gpu" ]; then
        cmd=$(pin_gpu "$cmd" "$gpu")
    fi
    # The launcher sits behind the entry point, where hydra documents '-m'.
    full="$PYTHON ${cmd%% *}$launcher ${cmd#* }${extra:+ $extra}"

    # A missing manifest means the training has not finished, the normal state
    # of most of a catalogue: report it and evaluate the ready blocks anyway.
    manifest=$(field "$cmd" 'checkpoint_manifest_path')
    if [ "$dry" -eq 0 ] && [ ! -f "$manifest" ]; then
        echo "warning: no manifest yet for $label ($manifest)" >&2
        n_missing=$((n_missing + 1))
    fi

    # The baseline is what the delta columns are measured against, so its
    # absence costs those columns and nothing else: the block still runs.
    baseline=$(field "$cmd" 'baseline_checkpoint_manifest_path')
    if [ "$dry" -eq 0 ] && [ -n "$baseline" ] && [ ! -f "$baseline" ]; then
        echo "warning: no baseline manifest yet for $label ($baseline)" >&2
        echo "         the row will be written without the delta columns." >&2
    fi

    n_sub=$((n_sub + 1))
    if [ "$dry" -eq 1 ]; then
        echo "[$i/$n_total] $full"
        continue
    fi
    if [ -z "$cluster" ]; then
        printf 'echo "[%d/%d] %s"\n%s || echo "FAILED: %s" >&2\n' \
            "$n_sub" "$n_total" "$label" "$full" "$label" >> "$queue"
        continue
    fi
    echo "[$i/$n_total] submitting: $label"
    nohup bash -c "$full" > "$logdir/${i}_${label}_${run_ts}.log" 2>&1 &
    sleep 1
done <<EOF
$cmds
EOF

if [ "$n_sub" -eq 0 ]; then
    echo "nothing matched --only '$only' in $file" >&2
    exit 1
fi
[ "$n_missing" -eq 0 ] || echo "$n_missing of $n_sub selected block(s) have no manifest yet." >&2

if [ "$dry" -eq 1 ]; then
    echo
    echo "$n_sub of $n_total command(s) would run."
elif [ -n "$cluster" ]; then
    echo
    echo "$n_sub of $n_total job(s) submitted (logs: $logdir)."
    echo "Jobs run under slurm; drivers are nohup'd, safe to log out."
    echo "Check the queue with: squeue --me"
else
    log="${queue%.sh}.log"
    nohup bash "$queue" > "$log" 2>&1 &
    echo
    echo "$n_sub of $n_total command(s) queued on GPU ${gpu:-0}, running detached."
    echo "Queue:  $queue"
    echo "Log:    $log"
fi
